import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';

const require = createRequire(new URL('../package.json', import.meta.url));
const styles = await Promise.all([
  'bpmn-js/dist/assets/diagram-js.css',
  'bpmn-js/dist/assets/bpmn-js.css',
].map(async path => readFile(require.resolve(path), 'utf8')));

// Ship the official CSS inside the lazy runtime, including Shadow DOM hosts.
// Consumers need neither a CSS loader nor a separate asset installation step.
const output = new URL('../src/bpmnVendorStyles.ts', import.meta.url);
const generated = '// Generated by scripts/build-bpmn-styles.mjs. Do not edit by hand.\n' +
  '// bpmn-js / diagram-js styles. See THIRD_PARTY_NOTICES.md.\n' +
  `export const bpmnVendorStyles: string = ${JSON.stringify(styles.join('\n'))};\n`;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== generated) throw new Error('BPMN vendor styles are stale.');
} else {
  await writeFile(output, generated);
}
